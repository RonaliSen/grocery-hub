export type ReminderType = 'expiry' | 'low-stock' | 'budget' | 'cart' | 'custom';

export type ReminderStatus = 'upcoming' | 'due-soon' | 'overdue' | 'completed';

export type ReminderTab = 'all' | ReminderType;

export type ReminderLifecycleStatus = 'ACTIVE' | 'SNOOZED' | 'COMPLETED' | 'DELETED';

export type ReminderLifecycleView = Exclude<ReminderLifecycleStatus, 'DELETED'>;

export type ReminderCompletionAction =
  | 'MARK_CONSUMED'
  | 'RESTOCKED'
  | 'PURCHASE_COMPLETED'
  | 'BUDGET_REVIEWED'
  | 'MARK_DONE'
  | 'ADDED_TO_CART';

export type ReminderHistoryStatus = 'completed' | 'dismissed' | 'resolved' | 'deleted' | 'snoozed';

export type ReminderRecurrence = 'one-time' | 'daily' | 'weekly' | 'monthly';

export type ReminderAction =
  | 'view-item'
  | 'mark-consumed'
  | 'add-to-cart'
  | 'view-expenses'
  | 'open-cart'
  | 'open-related';

export interface ReminderItem {
  readonly id: string;
  readonly baseId: string;
  readonly type: ReminderType;
  readonly title: string;
  readonly description: string;
  readonly status: ReminderStatus;
  readonly dueAt: string | null;
  readonly snoozedUntil: string | null;
  readonly countLabel: string | null;
  readonly relatedItemId: string | null;
  readonly relatedRoute: string;
  readonly actions: readonly ReminderAction[];
  readonly canMarkDone: boolean;
  readonly canDelete: boolean;
  readonly isAutoGenerated: boolean;
}

export interface ReminderHistoryEntry {
  readonly id: string;
  readonly reminderId: string;
  readonly reminderType: ReminderType;
  readonly title: string;
  readonly description: string;
  readonly status: ReminderHistoryStatus;
  readonly occurredAt: string;
}

export interface CustomReminderRecord {
  readonly id: string;
  readonly name: string;
  readonly recurrence: ReminderRecurrence;
  readonly date: string;
  readonly time: string | null;
  readonly notes: string | null;
  readonly createdAt: string;
  readonly updatedAt: string;
}

export interface CustomReminderDraft {
  readonly name: string;
  readonly recurrence: ReminderRecurrence;
  readonly date: string;
  readonly time: string | null;
  readonly notes: string | null;
}

export interface ReminderStateRecord {
  readonly baseId: string;
  readonly status: ReminderLifecycleStatus;
  readonly snoozedUntil: string | null;
  readonly updatedAt: string;
}

export interface ReminderAutoSnapshot {
  readonly reminderId: string;
  readonly baseId: string;
  readonly reminderType: Exclude<ReminderType, 'custom'>;
  readonly title: string;
  readonly description: string;
  readonly relatedItemId: string | null;
  readonly relatedRoute: string;
  readonly capturedAt: string;
}

export interface CompletedReminderRecord {
  readonly id: string;
  readonly reminderId: string;
  readonly baseId: string;
  readonly type: ReminderType;
  readonly title: string;
  readonly description: string;
  readonly relatedItemId: string | null;
  readonly relatedRoute: string;
  readonly completedAt: string;
  readonly completedByAction: ReminderCompletionAction;
  readonly completedType: ReminderType;
  readonly isAutoResolved: boolean;
  readonly customReminder: CustomReminderRecord | null;
}

export interface ReminderStore {
  readonly customReminders: readonly CustomReminderRecord[];
  readonly completed: readonly CompletedReminderRecord[];
  readonly history: readonly ReminderHistoryEntry[];
  readonly states: readonly ReminderStateRecord[];
  readonly activeAutoSnapshots: readonly ReminderAutoSnapshot[];
  readonly notifiedKeys: readonly string[];
}

export const DEFAULT_REMINDER_STORE: ReminderStore = {
  customReminders: [],
  completed: [],
  history: [],
  states: [],
  activeAutoSnapshots: [],
  notifiedKeys: []
};
